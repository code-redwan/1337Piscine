int	ft_atoi(char *str)
{
	int	result;
	int	sign;

	result = 0;
	sign = 0;
	while ((*str >= 9 && *str <= 13) || *str == 32)
		str++;
	while (*str == 43 || *str == 45)
	{
		if (*str == 45)
			sign++;
		str++;
	}
	while (*str >= 48 && *str <= 57)
	{
		result = (result * 10) + (*str - 48);
		str++;
	}
	if (sign % 2 != 0)
		return (result * (-1));
	return (result);
}
